-- =========================================================
-- TBILISI CAFE FINDER DATABASE
-- =========================================================


-- 1. ROLES
CREATE TABLE roles (
    role_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(50) UNIQUE NOT NULL
);


-- 2. USERS
CREATE TABLE users (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,

    role_id INT NOT NULL DEFAULT 1,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    inactive_since TIMESTAMP NULL,

    CONSTRAINT fk_users_role
        FOREIGN KEY (role_id)
        REFERENCES roles(role_id)
);


-- 3. AMENITIES
CREATE TABLE amenities (
    amenity_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) UNIQUE NOT NULL
);


-- 4. FOOD CATEGORIES
CREATE TABLE food_categories (
    category_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) UNIQUE NOT NULL
);


-- 5. CAFES
CREATE TABLE cafes (
    cafe_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(150) NOT NULL,
    description TEXT,

    neighborhood VARCHAR(100) NOT NULL,
    address VARCHAR(255) NOT NULL,

    latitude DECIMAL(9,6) NOT NULL,
    longitude DECIMAL(9,6) NOT NULL,

    price_level SMALLINT NOT NULL,

    opening_hours TEXT,
    image_url VARCHAR(500),

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_cafe_price
        CHECK (price_level BETWEEN 1 AND 3),

    CONSTRAINT chk_cafe_latitude
        CHECK (latitude BETWEEN -90 AND 90),

    CONSTRAINT chk_cafe_longitude
        CHECK (longitude BETWEEN -180 AND 180)
);


-- 6. USER PREFERENCES
CREATE TABLE user_preferences (
    user_id INT PRIMARY KEY,

    max_price_level SMALLINT,
    max_distance_km SMALLINT,

    preferred_food_category_id INT,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_preferences_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id),

    CONSTRAINT fk_preferences_food
        FOREIGN KEY (preferred_food_category_id)
        REFERENCES food_categories(category_id),

    CONSTRAINT chk_preference_price
        CHECK (
            max_price_level IS NULL
            OR max_price_level BETWEEN 1 AND 3
        ),

    CONSTRAINT chk_preference_distance
        CHECK (
            max_distance_km IS NULL
            OR max_distance_km IN (1, 3, 5)
        )
);


-- 7. FAVORITES
CREATE TABLE favorites (
    user_id INT,
    cafe_id INT,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (user_id, cafe_id),

    CONSTRAINT fk_favorites_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id),

    CONSTRAINT fk_favorites_cafe
        FOREIGN KEY (cafe_id)
        REFERENCES cafes(cafe_id)
);


-- 8. REVIEWS
CREATE TABLE reviews (
    review_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id INT NOT NULL,
    cafe_id INT NOT NULL,

    rating SMALLINT NOT NULL,
    review_text TEXT,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_reviews_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id),

    CONSTRAINT fk_reviews_cafe
        FOREIGN KEY (cafe_id)
        REFERENCES cafes(cafe_id),

    CONSTRAINT chk_review_rating
        CHECK (rating BETWEEN 1 AND 5),

    CONSTRAINT chk_review_length
        CHECK (
            review_text IS NULL
            OR char_length(review_text) <= 500
        ),

    CONSTRAINT uq_user_cafe_review
        UNIQUE (user_id, cafe_id)
);


-- 9. PREFERENCE AMENITIES
CREATE TABLE preference_amenities (
    user_id INT,
    amenity_id INT,

    selection VARCHAR(20) NOT NULL,

    PRIMARY KEY (user_id, amenity_id),

    CONSTRAINT fk_preference_amenities_user
        FOREIGN KEY (user_id)
        REFERENCES user_preferences(user_id),

    CONSTRAINT fk_preference_amenities_amenity
        FOREIGN KEY (amenity_id)
        REFERENCES amenities(amenity_id),

    CONSTRAINT chk_amenity_selection
        CHECK (
            selection IN (
                'required',
                'preferred',
                'no_preference'
            )
        )
);


-- 10. CAFE AMENITIES
CREATE TABLE cafe_amenities (
    cafe_id INT,
    amenity_id INT,

    PRIMARY KEY (cafe_id, amenity_id),

    CONSTRAINT fk_cafe_amenities_cafe
        FOREIGN KEY (cafe_id)
        REFERENCES cafes(cafe_id),

    CONSTRAINT fk_cafe_amenities_amenity
        FOREIGN KEY (amenity_id)
        REFERENCES amenities(amenity_id)
);


-- 11. CAFE FOOD CATEGORIES
CREATE TABLE cafe_food_categories (
    cafe_id INT,
    category_id INT,

    PRIMARY KEY (cafe_id, category_id),

    CONSTRAINT fk_cafe_food_cafe
        FOREIGN KEY (cafe_id)
        REFERENCES cafes(cafe_id),

    CONSTRAINT fk_cafe_food_category
        FOREIGN KEY (category_id)
        REFERENCES food_categories(category_id)
);